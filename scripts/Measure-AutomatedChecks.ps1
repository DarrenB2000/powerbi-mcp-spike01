<#
.SYNOPSIS
    Runs all automated (non-interactive) checks and outputs a Markdown report.
.DESCRIPTION
    Executes every check that does not require an AI agent session, a browser login, or
    a running Power BI Desktop instance as a hard requirement. Outputs a Markdown section
    suitable for pasting into docs/05-validation-results.md Section A.

    Includes:
      - Timestamp, OS, PowerShell version, shell info
      - VS Code version
      - Installed VS Code extensions (filtered to relevant ones)
      - .NET SDK list
      - Git version
      - Config file existence (.vscode/mcp.json, .mcp.json, CLAUDE.md,
        .github/copilot-instructions.md)
      - Local catalog summary (masked IDs)
      - Repo disk size
      - Power BI Desktop process count (no PII)
      - Test-McpConnectivity.ps1 output and timing
      - Initialize-Workspace.ps1 timing against a temp folder (reverted after)
.EXAMPLE
    .\Measure-AutomatedChecks.ps1
.EXAMPLE
    .\Measure-AutomatedChecks.ps1 | Out-File docs\05-validation-results-section-a.md -Encoding UTF8
#>
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Continue'

$workspaceRoot = Split-Path -Parent $PSScriptRoot
$lines         = [System.Collections.Generic.List[string]]::new()
$runAt         = (Get-Date).ToUniversalTime()

function Add ([string]$line) { $lines.Add($line) }
function AddBlank { $lines.Add('') }
function AddH2 ([string]$t) { $lines.Add("## $t"); $lines.Add('') }
function AddH3 ([string]$t) { $lines.Add("### $t"); $lines.Add('') }
function Safe-Run ([scriptblock]$sb) {
    try { & $sb } catch { "ERROR: $($_.Exception.Message)" }
}

# Mask all but last 4 chars of a GUID string
function Mask-Id ([string]$id) {
    if (-not $id -or $id.Length -lt 4) { return '...' }
    return '...' + $id.Substring($id.Length - 4)
}

#region Header
Add "## Section A: Automated checks"
AddBlank
Add ("_Generated by `scripts/Measure-AutomatedChecks.ps1` at {0} UTC_" -f $runAt.ToString('yyyy-MM-ddTHH:mm:ssZ'))
AddBlank
Add "---"
AddBlank
#endregion

#region Environment
AddH3 "Environment"
Add "| Property | Value |"
Add "|---|---|"
Add "| OS | $([System.Runtime.InteropServices.RuntimeInformation]::OSDescription) |"
Add "| Architecture | $([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture) |"
Add "| PowerShell edition | $($PSVersionTable.PSEdition) |"
Add "| PowerShell version | $($PSVersionTable.PSVersion) |"
Add "| Shell | PowerShell |"
Add "| Date / time (UTC) | $($runAt.ToString('o')) |"
AddBlank
#endregion

#region VS Code
AddH3 "VS Code"
$vsCodeRaw = Safe-Run { code --version 2>&1 }
Add '```'
foreach ($l in $vsCodeRaw) { Add $l }
Add '```'
AddBlank
#endregion

#region Extensions
AddH3 "VS Code extensions (relevant)"
$relevantPrefixes = @('GitHub.copilot', 'Analysis-services', 'ms-vscode', 'GitHub.copilot-chat')
$extList = Safe-Run { code --list-extensions 2>&1 }
$relevantExts = $extList | Where-Object {
    $ext = $_
    $relevantPrefixes | Where-Object { $ext -ilike "$_*" }
}
if ($relevantExts) {
    Add '```'
    foreach ($e in $relevantExts) { Add $e }
    Add '```'
} else {
    Add '_No relevant extensions found or VS Code not in PATH._'
}
AddBlank
#endregion

#region .NET SDKs
AddH3 ".NET SDKs"
$dotnetSdks = Safe-Run { dotnet --list-sdks 2>&1 }
Add '```'
foreach ($l in $dotnetSdks) { Add $l }
Add '```'
AddBlank
#endregion

#region Git
AddH3 "Git version"
$gitVer = Safe-Run { git --version 2>&1 }
Add '```'
Add $gitVer
Add '```'
AddBlank
#endregion

#region Config file existence
AddH3 "Configuration file presence"
$cfgFiles = @(
    @{ Path = '.vscode\mcp.json';               Label = '`.vscode/mcp.json`' }
    @{ Path = '.mcp.json';                      Label = '`.mcp.json`' }
    @{ Path = 'CLAUDE.md';                      Label = '`CLAUDE.md`' }
    @{ Path = '.github\copilot-instructions.md'; Label = '`.github/copilot-instructions.md`' }
)
Add "| File | Present |"
Add "|---|---|"
foreach ($cf in $cfgFiles) {
    $full    = Join-Path $workspaceRoot $cf.Path
    $present = if (Test-Path $full) { 'yes' } else { 'no' }
    Add "| $($cf.Label) | $present |"
}
AddBlank
#endregion

#region Local catalog summary
AddH3 "Local catalog (config/semantic-model-ids.local.json)"
$localCatalogPath = Join-Path $workspaceRoot 'config\semantic-model-ids.local.json'
if (Test-Path $localCatalogPath) {
    try {
        $catalog = Get-Content -Raw $localCatalogPath | ConvertFrom-Json
        Add "| Key | Value |"
        Add "|---|---|"
        if ($catalog.selectedWorkspace) {
            Add "| Selected workspace | $($catalog.selectedWorkspace.name) (id: $(Mask-Id $catalog.selectedWorkspace.id)) |"
        }
        if ($catalog.selectedModel) {
            Add "| Selected model | $($catalog.selectedModel.name) (id: $(Mask-Id $catalog.selectedModel.id)) |"
        }
        if ($catalog.localPbix) {
            $pbixName = if ($catalog.localPbix.pbixFileName) { $catalog.localPbix.pbixFileName } else { '(none)' }
            Add "| Local PBIX file | $pbixName (port: $($catalog.localPbix.localPort)) |"
        }
        if (-not $catalog.selectedWorkspace -and -not $catalog.selectedModel -and -not $catalog.localPbix) {
            Add "| (no entries) | Run Select-Workspace.ps1 or Get-OpenPbixModel.ps1 |"
        }
    } catch {
        Add "_Could not parse local catalog: $($_.Exception.Message)_"
    }
} else {
    Add "_File not present. Run `scripts\Select-Workspace.ps1` to create it._"
}
AddBlank
#endregion

#region Repo disk size
AddH3 "Repository disk size"
try {
    $sizeBytes = (Get-ChildItem -Path $workspaceRoot -Recurse -File -ErrorAction SilentlyContinue |
                  Measure-Object -Property Length -Sum).Sum
    $sizeKb    = [math]::Round($sizeBytes / 1KB, 1)
    Add "| Metric | Value |"
    Add "|---|---|"
    Add "| Total files | $((Get-ChildItem -Path $workspaceRoot -Recurse -File -ErrorAction SilentlyContinue).Count) |"
    Add "| Total size | ${sizeKb} KB |"
} catch {
    Add "_Could not calculate disk size: $($_.Exception.Message)_"
}
AddBlank
#endregion

#region Power BI Desktop process count
AddH3 "Power BI Desktop processes (Windows only)"
if ($env:OS -eq 'Windows_NT' -or $IsWindows) {
    $pbidProcs = @(Get-Process -Name 'PBIDesktop' -ErrorAction SilentlyContinue)
    $count = $pbidProcs.Count
    Add "| Metric | Value |"
    Add "|---|---|"
    Add "| PBIDesktop instances running | $count |"
    if ($count -gt 0) {
        Add "| PIDs | $($pbidProcs.Id -join ', ') |"
        # Check for port files
        $portDir   = "$env:LOCALAPPDATA\Microsoft\Power BI Desktop\AnalysisServicesWorkspaces"
        $portFiles = @(Get-ChildItem -Path $portDir -Filter 'msmdsrv.port.txt' -Recurse -ErrorAction SilentlyContinue)
        Add "| msmdsrv.port.txt files found | $($portFiles.Count) |"
    }
} else {
    Add "_Not running on Windows. Power BI Desktop detection skipped._"
}
AddBlank
#endregion

#region Test-McpConnectivity.ps1 timing
AddH3 "Test-McpConnectivity.ps1 result and timing"
$smokeScriptPath = Join-Path $PSScriptRoot 'Test-McpConnectivity.ps1'
if (Test-Path $smokeScriptPath) {
    $smokeOutput     = [System.Collections.Generic.List[string]]::new()
    $smokeExitCode   = $null
    $smokeTiming     = Measure-Command {
        $smokeOutput.AddRange([string[]](& powershell.exe -NoProfile -File $smokeScriptPath 2>&1))
        $smokeExitCode = $LASTEXITCODE
    }
    Add "| Metric | Value |"
    Add "|---|---|"
    Add "| Exit code | $smokeExitCode |"
    Add "| Elapsed (ms) | $([math]::Round($smokeTiming.TotalMilliseconds)) |"
    AddBlank
    Add '```'
    foreach ($l in $smokeOutput) { Add $l }
    Add '```'
} else {
    Add "_Test-McpConnectivity.ps1 not found._"
}
AddBlank
#endregion

#region Initialize-Workspace.ps1 timing (temp dir)
AddH3 "Initialize-Workspace.ps1 timing (temp folder)"
$initScriptPath = Join-Path $PSScriptRoot 'Initialize-Workspace.ps1'
$tempDir        = $null
if (Test-Path $initScriptPath) {
    try {
        # Create a temp workspace with the config/ folder so the init script can find templates
        $tempDir = New-Item -ItemType Directory -Path ([System.IO.Path]::GetTempPath()) `
            -Name "spike-init-test-$([Guid]::NewGuid().ToString('N')[0..7] -join '')" -Force
        $tempConfigDir = Join-Path $tempDir.FullName 'config'
        $tempScriptsDir = Join-Path $tempDir.FullName 'scripts'
        New-Item -ItemType Directory -Path $tempConfigDir  -Force | Out-Null
        New-Item -ItemType Directory -Path $tempScriptsDir -Force | Out-Null

        # Copy config examples to temp workspace
        $configSrc = Join-Path $workspaceRoot 'config'
        Copy-Item -Path (Join-Path $configSrc '*.example') -Destination $tempConfigDir -ErrorAction SilentlyContinue
        Copy-Item -Path (Join-Path $configSrc '*.md')      -Destination $tempConfigDir -ErrorAction SilentlyContinue

        $initOutput  = [System.Collections.Generic.List[string]]::new()
        $initTiming  = Measure-Command {
            $initOutput.AddRange([string[]](& powershell.exe -NoProfile -File $initScriptPath `
                -WorkspaceRoot $tempDir.FullName 2>&1))
        }
        Add "| Metric | Value |"
        Add "|---|---|"
        Add "| Elapsed (ms) | $([math]::Round($initTiming.TotalMilliseconds)) |"
        Add "| Temp folder | (cleaned up after measurement) |"
        AddBlank
        Add '```'
        foreach ($l in $initOutput) { Add $l }
        Add '```'
    } catch {
        Add "_Initialize-Workspace.ps1 timing failed: $($_.Exception.Message)_"
    } finally {
        if ($tempDir -and (Test-Path $tempDir.FullName)) {
            Remove-Item -Path $tempDir.FullName -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
} else {
    Add "_Initialize-Workspace.ps1 not found._"
}
AddBlank
#endregion

Add "---"
AddBlank
Add "_End of automated checks._"

# Output to stdout
$lines | ForEach-Object { Write-Output $_ }
